        /// <summary>
        /// Returns the catalog description for a command, so saved copies of catalog commands also get one.
        /// </summary>
        internal static string GetDescription(string command)
        {
            if (string.IsNullOrWhiteSpace(command))
                return null;

            var trimmed = command.Trim();
            foreach (var entry in All)
            {
                if (string.Equals(entry.command, trimmed, StringComparison.OrdinalIgnoreCase))
                    return entry.description;
            }
            return null;
        }
